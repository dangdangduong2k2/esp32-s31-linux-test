"""Build the fixed rgb-led DT overlay without host dtc dependencies.

Writes both the readable DTS and its equivalent FDT v17 encoding. This is
a serializer for the tree below, NOT a general DTS compiler. FDT structure:
https://devicetree-specification.readthedocs.io/en/stable/flattened-format.html
"""
import argparse
from pathlib import Path
import struct


def cells(*values):
    return struct.pack('>' + 'I' * len(values), *values)


def string(value):
    return value.encode('ascii') + b'\0'


def tree():
    # (name, properties, children). External phandles are resolved by Linux.
    def fragment(index, symbol, props, children=()):
        return (f'fragment@{index}', {'target': cells(0xffffffff)}, [
            ('__overlay__', props, list(children))])

    return ('', {
        'espressif,overlay-name': string('rgb-led'),
        'espressif,resource-claims': string('gpspi2'),
    }, [
        fragment(0, 'axi_gdma', {'status': string('okay')}),
        fragment(1, 'gpspi2_default', {}, [
            ('spi-pins', {
                'espressif,route-names': string('rgb-led.data'),
                'espressif,route-kinds': string('matrix-output'),
                # ESP32S31_MATRIX_OUT(GPIO60, GPSPI2 MOSI signal 55, 0).
                'pinmux': cells(0x1000373c),
            }, []),
        ]),
        fragment(2, 'gpspi2', {
            '#address-cells': cells(1), '#size-cells': cells(0),
            'status': string('okay'),
        }, [('spidev@0', {
            'compatible': string('rohm,dh2228fv'),
            'reg': cells(0), 'spi-max-frequency': cells(3200000),
        }, [])]),
        ('__fixups__', {
            'axi_gdma': string('/fragment@0:target:0'),
            'gpspi2_default': string('/fragment@1:target:0'),
            'gpspi2': string('/fragment@2:target:0'),
        }, []),
    ])


def serialize(root):
    names = bytearray()
    offsets = {}
    block = bytearray()

    def padded(data):
        return data + b'\0' * (-len(data) % 4)

    def node(item):
        name, props, children = item
        block.extend(cells(1) + padded(string(name)))  # FDT_BEGIN_NODE
        for key, value in props.items():
            if key not in offsets:
                offsets[key] = len(names)
                names.extend(string(key))
            block.extend(cells(3, len(value), offsets[key]) + padded(value))
        for child in children:
            node(child)
        block.extend(cells(2))  # FDT_END_NODE

    node(root)
    block.extend(cells(9))  # FDT_END
    start = 40 + 16  # header plus empty 64-bit reservation pair
    header = cells(0xd00dfeed, start + len(block) + len(names), start,
                   start + len(block), 40, 17, 16, 0, len(names), len(block))
    return header + bytes(16) + block + names


def source(root):
    lines = ['// SPDX-License-Identifier: MIT',
             '// Generated by led/build-overlay.py; do not edit separately.',
             '/dts-v1/;', '/plugin/;', '']
    numeric = {'target', 'pinmux', 'reg', '#address-cells',
               '#size-cells', 'spi-max-frequency'}

    def node(item, depth):
        name, props, children = item
        indent = '    ' * depth
        lines.append(indent + (name or '/') + ' {')
        for key, value in props.items():
            if key in numeric:
                val = '<' + ' '.join(f'0x{v:x}' for v in struct.unpack('>' + 'I' * (len(value)//4), value)) + '>'
            else:
                val = '"' + value.rstrip(b'\0').decode('ascii') + '"'
            lines.append(indent + '    ' + key + ' = ' + val + ';')
        for child in children:
            node(child, depth + 1)
        lines.append(indent + '};')

    node(root, 0)
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    args.out.joinpath('esp32s31-overlay-rgb-led.dtbo').write_bytes(serialize(tree()))
    args.out.joinpath('rgb-led.dtso').write_text(source(tree()), encoding='utf-8', newline='\n')
